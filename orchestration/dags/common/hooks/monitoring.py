def _get_airflow_invocation_ids() -> Set[str]:
    """invocation_ids of dbt invocations that elementary detected as triggered
    by Airflow (orchestrator = 'airflow' in dbt_invocations), so that runs
    from other sources (local dev, CI, ...) hitting the same elementary
    dataset don't get counted in the report.
    """
    dataset = f"dbt_artifacts_{ENV_SHORT_NAME}"
    # No ORCHESTRATOR/DBT_ORCHESTRATOR var is set in this repo, so elementary
    # falls back to auto-detecting orchestrator='airflow' from AIRFLOW_HOME
    # being set in the environment running dbt, which is true for every task
    # in this repo.
    # Docs: https://docs.elementary-data.com/oss/guides/collect-job-data
    # Macro: https://github.com/elementary-data/dbt-data-reliability/blob/master/macros/edr/dbt_artifacts/upload_dbt_invocation.sql
    query = f"""
        SELECT DISTINCT invocation_id
        FROM `{GCP_PROJECT_ID}.{dataset}.dbt_invocations`
        WHERE orchestrator = 'airflow'
    """
    return set(BigQueryClient().query(query)["invocation_id"])


def _dedup_runs_by_last_invocation_per_day(
    runs: List[ModelRunSchema],
) -> List[ModelRunSchema]:
    """Keep only the last invocation of each node for each calendar day.

    Elementary counts every dbt invocation it finds in the lookback window as
    its own run. When an Airflow task retry re-runs a node after a transient
    failure (see dbt_run_dag's retries), the earlier failed invocation is
    still reported as a failure alongside the later successful one, inflating
    failure counts for nodes that are actually healthy. Collapsing to the
    last invocation per node per day reflects the day's real outcome.
    """
    latest_run_per_node_and_day = {}
    for run in runs:
        day = datetime.fromisoformat(run.generated_at).date()
        key = (run.unique_id, day)
        current_latest = latest_run_per_node_and_day.get(key)
        if current_latest is None or run.generated_at > current_latest.generated_at:
            latest_run_per_node_and_day[key] = run
    return list(latest_run_per_node_and_day.values())


_original_models_fetcher_get_models_runs = ModelsFetcher.get_models_runs


def _get_models_runs_deduped_by_day(
    self, days_back: int = 7, exclude_elementary_models: bool = False
) -> List[ModelRunSchema]:
    runs = _original_models_fetcher_get_models_runs(
        self, days_back=days_back, exclude_elementary_models=exclude_elementary_models
    )
    airflow_invocation_ids = _get_airflow_invocation_ids()
    runs = [run for run in runs if run.invocation_id in airflow_invocation_ids]
    return _dedup_runs_by_last_invocation_per_day(runs)


# Patch at import time so every report generated by this hook is deduped,
# since elementary has no built-in option for this.
ModelsFetcher.get_models_runs = _get_models_runs_deduped_by_day


class ElementaryReport:
    def generate_report(self, report_file_path: str, days_back: int = 7) -> bool:
        """
        Generate monitoring report

        Args:
            days_back: Number of days to look back for report. Default is 7.
            report_file_path: Path to save the report file
        """
        # elementary's dbt_project.yml uses env_var('DBT_PACKAGES_FOLDER', 'dbt_packages')
        # for packages-install-path; redirect to /tmp to avoid Permission denied in site-packages
        dbt_package_folder = os.environ.get("DBT_PACKAGES_FOLDER")
        os.environ["DBT_PACKAGES_FOLDER"] = "/tmp/dbt_packages"

        config = Config(
            config_dir=PATH_TO_DBT_PROJECT,
            profiles_dir=PATH_TO_DBT_PROJECT,
            project_dir=PATH_TO_DBT_PROJECT,
            profile_target=ENV_SHORT_NAME,
            target_path=PATH_TO_DBT_TARGET,
            gcs_bucket_name=DE_BIGQUERY_DATA_EXPORT_BUCKET_NAME,
            env=ENV_SHORT_NAME,
            run_dbt_deps_if_needed=True,
        )
        anonymous_tracking = AnonymousCommandLineTracking(config)
        config.validate_send_report()

        data_monitoring = DataMonitoringReport(
            config=config,
            tracking=anonymous_tracking,
            force_update_dbt_package=False,
            disable_samples=False,
        )

        if dbt_package_folder:
            os.environ["DBT_PACKAGES_FOLDER"] = dbt_package_folder

        return data_monitoring.send_report(
            days_back=days_back,
            test_runs_amount=720,
            disable_passed_test_metrics=False,
            should_open_browser=False,
            exclude_elementary_models=False,
            project_name=None,
            remote_file_path=report_file_path,
            disable_html_attachment=True,
            include_description=False,
        )

    def send_monitoring_report(
        self,
        slack_channel: str,
        slack_token: str,
        slack_group_alerts_by: str = "table",
        global_suppression_interval: int = 24,
        days_back: int = 1,
    ) -> bool:
        """
        Send monitoring report to slack channel

        Args:
            slack_channel: Slack channel name
            slack_token: Slack token
            slack_group_alerts_by: Slack group alerts by table or model. Default is table.
            global_suppression_interval: Number of hours to wait before sending the same alert again. Default is 24.
            days_back: Number of days to look back for alerts. Default is 1.
        """
        # elementary's dbt_project.yml uses env_var('DBT_PACKAGES_FOLDER', 'dbt_packages')
        # for packages-install-path; redirect to /tmp to avoid Permission denied in site-packages
        dbt_package_folder = os.environ.get("DBT_PACKAGES_FOLDER")

        os.environ["DBT_PACKAGES_FOLDER"] = "/tmp/dbt_packages"

        config = Config(
            config_dir=PATH_TO_DBT_PROJECT,
            profiles_dir=PATH_TO_DBT_PROJECT,
            project_dir=PATH_TO_DBT_PROJECT,
            profile_target=ENV_SHORT_NAME,
            target_path=PATH_TO_DBT_TARGET,
            env=ENV_SHORT_NAME,
            run_dbt_deps_if_needed=True,
            slack_channel_name=slack_channel,
            slack_token=slack_token,
            slack_group_alerts_by=slack_group_alerts_by,
            report_url=ELEMENTARY_REPORT_URL,
        )
        anonymous_tracking = AnonymousCommandLineTracking(config)
        config.validate_monitor()
        data_monitoring = DataMonitoringAlerts(
            config=config,
            tracking=anonymous_tracking,
            force_update_dbt_package=False,
            send_test_message_on_success=True,
            disable_samples=False,
            selector_filter=FiltersSchema(),
            global_suppression_interval=global_suppression_interval,
            override_config=False,
        )

        results = data_monitoring.run_alerts(
            days_back=days_back,
            dbt_full_refresh=False,
            dbt_vars=None,
        )

        if dbt_package_folder:
            os.environ["DBT_PACKAGES_FOLDER"] = dbt_package_folder

        return results
